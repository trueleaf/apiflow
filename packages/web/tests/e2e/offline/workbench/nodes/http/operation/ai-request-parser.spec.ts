import { test, expect } from '../../../../../../fixtures/desktop.fixture'

test('自然语言请求预览、校验、合并和整体撤销重做', async ({ contentPage, clearCache, reload, createProject, createNode }) => {
  test.setTimeout(90000)
  await clearCache()
  await contentPage.evaluate(() => localStorage.setItem('apiflow/ai/llmProvider', JSON.stringify({ id: 'parser-test', name: 'parser-test', provider: 'custom', baseURL: 'http://127.0.0.1:3456', apiKey: 'mock-key', model: 'mock-model', customHeaders: [], extraBody: '' })))
  await reload()
  await createProject()
  await createNode(contentPage, { nodeType: 'http', name: '自然语言请求' })
  // 仅替换模型返回，页面交互和请求应用走真实流程
  await contentPage.evaluate(() => { window.desktopAPI!.aiManager.chat = (() => ({ choices: [{ message: { content: JSON.stringify({ method: 'POST', url: 'https://example.com/users', query: [{ key: 'page', value: '2' }], headers: [{ key: 'Authorization', value: 'Bearer {{token}}' }], body: { name: '张三', age: 28, enabled: true } }) } }] })) as typeof window.desktopAPI.aiManager.chat })
  const url = contentPage.locator('[data-testid="url-input"] [contenteditable]').first()
  await url.fill('https://example.com/old?keep=yes')
  await contentPage.locator('.pre-url-wrap').click()
  await url.click()
  await contentPage.keyboard.press('ControlOrMeta+a')
  await contentPage.evaluate(() => navigator.clipboard.writeText('POST https://example.com/users，page 为 2，name 是张三'))
  await contentPage.keyboard.press('ControlOrMeta+v')
  const dialog = contentPage.getByTestId('ai-request-parser')
  await expect(dialog).toBeVisible()
  await expect(url).toHaveText('https://example.com/old')
  await contentPage.getByTestId('ai-parser-analyze').click()
  const result = contentPage.getByTestId('ai-parser-result')
  await expect(result).toHaveValue(/张三/)
  await expect(dialog.locator('.ai-parser-comparison section').last()).toContainText('keep')
  // 非法候选数据不能应用，修复后才允许提交
  const valid = await result.inputValue()
  await result.fill('{"method":"INVALID"}')
  await expect(contentPage.getByTestId('ai-parser-apply')).toBeDisabled()
  await result.fill('{"url":"http://localhost:{{port}}/users"}')
  await expect(contentPage.getByTestId('ai-parser-apply')).toBeEnabled()
  await result.fill(valid)
  await contentPage.getByTestId('ai-parser-apply').click()
  await expect(url).toHaveText('https://example.com/users')
  await expect(contentPage.getByTestId('method-select')).toContainText('POST')
  await contentPage.getByTestId('http-params-undo-btn').first().click()
  await expect(url).toHaveText('https://example.com/old')
  await expect(contentPage.getByTestId('method-select')).toContainText('GET')
  await contentPage.getByTestId('http-params-redo-btn').first().click()
  await expect(url).toHaveText('https://example.com/users')
  await expect(contentPage.getByTestId('method-select')).toContainText('POST')
  // 再次打开预览，确认合并参数和请求体已落地
  await contentPage.getByTestId('url-ai-parser').click()
  await contentPage.getByTestId('ai-parser-description').fill('将 page 设置为 2')
  await contentPage.getByTestId('ai-parser-analyze').click()
  await expect(dialog.locator('.ai-parser-comparison section').first()).toContainText('Bearer {{token}}')
  await expect(dialog.locator('.ai-parser-comparison section').first()).toContainText('keep')
  await expect(dialog.locator('.ai-parser-comparison section').first()).toContainText('张三')
  // 请求在预览期间被全局撤销后，候选结果不能覆盖当前内容
  await contentPage.keyboard.press('ControlOrMeta+z')
  await expect(dialog).toContainText('当前请求已变化')
  await expect(contentPage.getByTestId('ai-parser-apply')).toBeDisabled()
})

test('JSON 自然语言生成和修改保留类型，失败与取消不覆盖原文', async ({ contentPage, clearCache, reload, createProject, createNode }) => {
  test.setTimeout(90000)
  await clearCache()
  await contentPage.evaluate(() => localStorage.setItem('apiflow/ai/llmProvider', JSON.stringify({ id: 'parser-test', name: 'parser-test', provider: 'custom', baseURL: 'http://127.0.0.1:3456', apiKey: 'mock-key', model: 'mock-model', customHeaders: [], extraBody: '' })))
  await reload()
  await createProject()
  await createNode(contentPage, { nodeType: 'http', name: '自然语言 JSON' })
  await contentPage.evaluate(() => { window.desktopAPI!.aiManager.chat = ((request) => {
      const user: { description: string; current?: string } = JSON.parse(request.messages[1].content)
      return { choices: [{ message: { content: user.description === '失败' ? 'invalid json' : JSON.stringify({ body: user.current ? { ...JSON.parse(user.current), age: 30 } : { name: '张三', age: 28, enabled: true, code: '001', roles: ['admin', 'editor'] } }) } }] }
    }) as typeof window.desktopAPI.aiManager.chat })
  await contentPage.getByRole('tab', { name: /^Body/ }).click()
  await contentPage.locator('.body-params').getByRole('radio', { name: 'json', exact: true }).check()
  // 通过剪贴板触发 JSON 编辑器的自然语言入口
  const editor = contentPage.locator('.body-params .json-wrap .monaco-editor')
  await contentPage.locator('.body-params .no-tip').click()
  await editor.click()
  await contentPage.evaluate(() => navigator.clipboard.writeText('生成用户：name 是张三，age 是 28，enabled 是 true'))
  await contentPage.keyboard.press('ControlOrMeta+v')
  await expect(contentPage.getByTestId('ai-request-parser')).toBeVisible()
  await contentPage.getByTestId('ai-parser-analyze').click()
  const result = contentPage.getByTestId('ai-parser-result')
  await expect(result).toHaveValue(/张三/)
  expect(JSON.parse(await result.inputValue())).toEqual({ name: '张三', age: 28, enabled: true, code: '001', roles: ['admin', 'editor'] })
  await contentPage.getByTestId('ai-parser-apply').click()
  await expect(editor).toContainText('张三')
  // 修改模式携带当前 JSON，并支持一次撤销
  await contentPage.getByTestId('body-ai-parser').click()
  await contentPage.getByTestId('ai-request-parser').locator('.el-radio-button').filter({ hasText: '修改当前 JSON' }).click()
  await contentPage.getByTestId('ai-parser-description').fill('将 age 改为 30')
  await contentPage.getByTestId('ai-parser-analyze').click()
  await expect(result).toHaveValue(/30/)
  expect(JSON.parse(await result.inputValue())).toMatchObject({ age: 30, code: '001', roles: ['admin', 'editor'] })
  await contentPage.getByTestId('ai-parser-apply').click()
  await expect(editor).toContainText('30')
  await contentPage.getByTestId('http-params-undo-btn').first().click()
  await expect(editor).toContainText('28')
  await contentPage.getByTestId('body-ai-parser').click()
  await contentPage.getByTestId('ai-parser-description').fill('失败')
  await contentPage.getByTestId('ai-parser-analyze').click()
  await expect(contentPage.getByTestId('ai-request-parser')).toContainText('解析失败')
  await expect(contentPage.getByTestId('ai-parser-apply')).toBeDisabled()
  await contentPage.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  await expect(editor).toContainText('28')
})

test('普通粘贴不触发 AI，取消解析后丢弃迟到结果', async ({ contentPage, clearCache, reload, createProject, createNode }) => {
  test.setTimeout(90000)
  await clearCache()
  await contentPage.evaluate(() => localStorage.setItem('apiflow/ai/llmProvider', JSON.stringify({ id: 'parser-test', name: 'parser-test', provider: 'custom', baseURL: 'http://127.0.0.1:3456', apiKey: 'mock-key', model: 'mock-model', customHeaders: [], extraBody: '' })))
  await reload()
  await createProject()
  await createNode(contentPage, { nodeType: 'http', name: '取消自然语言解析' })
  const url = contentPage.locator('[data-testid="url-input"] [contenteditable]').first()
  await url.click()
  await contentPage.keyboard.press('ControlOrMeta+a')
  await contentPage.evaluate(() => navigator.clipboard.writeText('https://example.com/请求/中文，路径'))
  await contentPage.keyboard.press('ControlOrMeta+v')
  await expect(url).toHaveText('https://example.com/请求/中文，路径')
  await expect(contentPage.getByTestId('ai-request-parser')).toHaveCount(0)
  // 延迟模型返回，取消等待后确认迟到数据不会进入预览或请求
  await contentPage.evaluate(() => { window.desktopAPI!.aiManager.chat = (async () => {
      await new Promise(resolve => setTimeout(resolve, 1500))
      return { choices: [{ message: { content: '{"url":"https://example.com/late"}' } }] }
    }) as typeof window.desktopAPI.aiManager.chat })
  await contentPage.getByTestId('url-ai-parser').click()
  await contentPage.getByTestId('ai-parser-description').fill('请求 https://example.com/late')
  await contentPage.getByTestId('ai-parser-analyze').click()
  await contentPage.getByTestId('ai-request-parser').getByRole('button', { name: '取消', exact: true }).click()
  await contentPage.waitForTimeout(2000)
  await expect(contentPage.getByTestId('ai-parser-result')).toHaveCount(0)
  await expect(contentPage.getByTestId('ai-parser-apply')).toBeDisabled()
  await expect(url).toHaveText('https://example.com/请求/中文，路径')
})
